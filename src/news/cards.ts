// Share cards for social networks: one JPEG per screen with the title, the bubble and the sources burned in,
// rendered from the same drawings as the site (no text in the drawings), in any language of the edition.
import { Resvg } from "@resvg/resvg-js";
import opentype from "opentype.js";
import jpeg from "jpeg-js";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { ROOT, GEN_DIR, readEdition, pick, type NewsStory } from "../content";

const FONT_DIR = join(ROOT, "assets", "fonts");
const FILES = {
  letter: join(FONT_DIR, "PatrickHandSC-Regular.ttf"),
  bold: join(FONT_DIR, "IBMPlexSansCondensed-Bold.ttf"),
  semi: join(FONT_DIR, "IBMPlexSansCondensed-SemiBold.ttf"),
  regular: join(FONT_DIR, "IBMPlexSansCondensed-Regular.ttf"),
};
const fonts = {
  letter: opentype.parse(readFileSync(FILES.letter).buffer as ArrayBuffer),
  bold: opentype.parse(readFileSync(FILES.bold).buffer as ArrayBuffer),
  regular: opentype.parse(readFileSync(FILES.regular).buffer as ArrayBuffer),
};

const W = 1080, H = 1350; // 4:5 portrait: Instagram's tallest feed format, fine on X and LinkedIn
const M = 48;              // side margin

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));

function wrap(font: opentype.Font, text: string, size: number, max: number): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = []; let cur = "";
  for (const w of words) {
    const tryLine = cur ? cur + " " + w : w;
    if (font.getAdvanceWidth(tryLine, size) <= max || !cur) cur = tryLine;
    else { lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  return lines;
}
/** Largest size between min and max at which the text fits in maxLines. */
function fit(font: opentype.Font, text: string, maxSize: number, minSize: number, width: number, maxLines: number) {
  for (let size = maxSize; size >= minSize; size -= 2) {
    const lines = wrap(font, text, size, width);
    if (lines.length <= maxLines) return { size, lines };
  }
  return { size: minSize, lines: wrap(font, text, minSize, width) };
}

const LABELS: Record<string, { says: string; sources: string; ai: string; style: string }> = {
  fr: { says: "{who} :", sources: "Sources :", ai: "Texte et dessin générés par IA", style: "Style :" },
  en: { says: "{who}:", sources: "Sources:", ai: "Text and drawings generated by AI", style: "Style:" },
};

export interface CardOpts { series: string; day: string; storyId: string; slide: number; lang: string; dateLabel: string; brand?: string }

/** Renders one screen of a story as a 1080×1350 JPEG. */
export function renderCard(o: CardOpts): Uint8Array {
  const ed = readEdition(o.series, o.day);
  const st = ed?.stories.find((s) => s.id === o.storyId) as NewsStory | undefined;
  if (!ed || !st) throw new Error("sujet introuvable");
  const sl = st.slides[o.slide];
  if (!sl) throw new Error("écran introuvable");
  const imgPath = join(GEN_DIR, o.series, "episodes", o.day, sl.image);
  if (!existsSync(imgPath)) throw new Error("image introuvable");
  const ext = sl.image.toLowerCase().endsWith(".png") ? "png" : "jpeg";
  const b64 = readFileSync(imgPath).toString("base64");
  const L = LABELS[o.lang] || LABELS.en;
  const first = o.slide === 0, last = o.slide === st.slides.length - 1;
  const brand = o.brand || "storink.com";

  // drawing: cover the card, anchored slightly above centre (heads and skies matter more than floors)
  const iw = sl.w || 1024, ih = sl.h || 1536;
  const scale = Math.max(W / iw, H / ih);
  const dw = iw * scale, dh = ih * scale;
  const dx = (W - dw) / 2, dy = Math.min(0, (H - dh) * 0.35);

  const parts: string[] = [];
  parts.push(`<image href="data:image/${ext};base64,${b64}" x="${dx}" y="${dy}" width="${dw}" height="${dh}" preserveAspectRatio="none"/>`);
  parts.push(`<defs>
<linearGradient id="top" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#000" stop-opacity="${first ? 0.82 : 0.55}"/><stop offset="1" stop-color="#000" stop-opacity="0"/></linearGradient>
<linearGradient id="bot" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="0.7"/></linearGradient>
</defs>`);
  parts.push(`<rect x="0" y="0" width="${W}" height="${first ? 560 : 170}" fill="url(#top)"/>`);
  parts.push(`<rect x="0" y="${H - 420}" width="${W}" height="420" fill="url(#bot)"/>`);

  // header: brand + date + position
  parts.push(`<text x="${M}" y="74" font-family="IBM Plex Sans Condensed" font-weight="700" font-size="34" fill="#fff">STORINK DAILY</text>`);
  parts.push(`<text x="${W - M}" y="74" text-anchor="end" font-family="IBM Plex Sans Condensed" font-size="30" fill="#ffffffcc">${esc(o.dateLabel)} · ${o.slide + 1}/${st.slides.length}</text>`);

  // title on the first screen
  if (first) {
    const t = fit(fonts.bold, pick(st.headline, o.lang), 84, 56, W - 2 * M, 4);
    t.lines.forEach((line, i) => parts.push(`<text x="${M}" y="${170 + i * t.size * 1.04}" font-family="IBM Plex Sans Condensed" font-weight="700" font-size="${t.size}" fill="#fff">${esc(line)}</text>`));
  }

  // bubble
  const who = sl.kind === "speech" && sl.speaker ? pick(sl.speaker, o.lang) : "";
  const raw = pick(sl.text, o.lang);
  const text = who ? `“${raw}”` : raw;
  const bw = W - 2 * M, pad = 30;
  const tb = fit(fonts.letter, text, 50, 36, bw - 2 * pad, 6);
  const lineH = tb.size * 1.2;
  const whoH = who ? 40 : 0;
  const bh = pad * 2 + whoH + tb.lines.length * lineH - (lineH - tb.size);
  const footH = last ? 92 : 46;
  const by = H - footH - 24 - bh;
  parts.push(`<rect x="${M + 9}" y="${by + 9}" width="${bw}" height="${bh}" rx="${who ? 34 : 6}" fill="#000" fill-opacity=".6"/>`);
  parts.push(`<rect x="${M}" y="${by}" width="${bw}" height="${bh}" rx="${who ? 34 : 6}" fill="#fbf6ea" stroke="#16181d" stroke-width="4"/>`);
  if (who) parts.push(`<text x="${M + pad}" y="${by + pad + 26}" font-family="IBM Plex Sans Condensed" font-weight="600" font-size="28" fill="#555">${esc(L.says.replace("{who}", who))}</text>`);
  tb.lines.forEach((line, i) => parts.push(`<text x="${M + pad}" y="${by + pad + whoH + tb.size * 0.82 + i * lineH}" font-family="Patrick Hand SC" font-size="${tb.size}" fill="#16181d">${esc(line)}</text>`));

  // footer: sources + AI notice on the last screen, the site address on every screen
  if (last) {
    const src = `${L.sources} ${st.sources.map((s) => s.name).join(", ")}`;
    const srcLine = fit(fonts.regular, src, 28, 22, W - 2 * M, 1).lines[0];
    parts.push(`<text x="${M}" y="${H - 76}" font-family="IBM Plex Sans Condensed" font-size="26" fill="#ffffffe0">${esc(srcLine)}</text>`);
  }
  parts.push(`<text x="${M}" y="${H - 30}" font-family="IBM Plex Sans Condensed" font-size="26" fill="#ffffffc0">${esc(L.ai)} · ${esc(pick(st.style?.name, o.lang))}</text>`);
  parts.push(`<text x="${W - M}" y="${H - 30}" text-anchor="end" font-family="IBM Plex Sans Condensed" font-weight="700" font-size="28" fill="#fff">${esc(brand)}</text>`);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}"><rect width="${W}" height="${H}" fill="#12161f"/>${parts.join("")}</svg>`;
  const r = new Resvg(svg, { font: { fontFiles: Object.values(FILES), loadSystemFonts: false, defaultFontFamily: "IBM Plex Sans Condensed" }, fitTo: { mode: "original" } });
  const img = r.render();
  // RGBA → JPEG (Instagram accepts JPEG only)
  const out = jpeg.encode({ data: Buffer.from(img.pixels), width: img.width, height: img.height }, 88);
  return new Uint8Array(out.data);
}

/** Post text for a story, per language (the link is added by each network's poster). */
export function storyCaption(series: string, day: string, storyId: string, lang: string): { headline: string; text: string } {
  const ed = readEdition(series, day);
  const st = ed?.stories.find((s) => s.id === storyId);
  if (!st) throw new Error("sujet introuvable");
  const headline = pick(st.headline, lang);
  const first = pick(st.slides[0]?.text, lang);
  return { headline, text: `${headline}\n\n${first}` };
}
